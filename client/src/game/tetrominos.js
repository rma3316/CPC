/** 7-bag 랜덤 생성기 */
export function createBag() {
  const pieces = Object.keys(TETROMINOS);
  // Fisher-Yates shuffle
  for (let i = pieces.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pieces[i], pieces[j]] = [pieces[j], pieces[i]];
  }
  return pieces;
}
